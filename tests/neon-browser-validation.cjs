// Run only against a fresh `npm run dev:isolated` (PGlite in memory).
const { chromium } = require(process.argv[2] || 'playwright');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'pt-BR', timezoneId: 'America/Sao_Paulo' });
  const page = await context.newPage(); const errors = []; const flows = [];
  page.on('pageerror', e => errors.push(e.message));
  const key = 'organizacao_financeira_store_v1'; const sentinel = '{"legacy":"preserve-exactly"}';
  await page.addInitScript(({ key, sentinel }) => { if (!localStorage.getItem(key)) localStorage.setItem(key, sentinel); }, { key, sentinel });
  await page.clock.setFixedTime(new Date('2026-09-21T12:00:00-03:00'));
  const sync = async () => { await page.waitForFunction(() => !document.querySelector('[role="status"]')); };
  const read = async month => page.evaluate(async month => (await fetch('/api/finance?month=' + month)).json(), month);
  const command = async (action, month, data = {}) => page.evaluate(async ({ action, month, data }) => {
    const { createFinanceApi } = await import('/src/services/financeApi.ts'); const api = createFinanceApi();
    const view = await api.read(month); await api.command(action, month, view.revision, data); return api.read(month);
  }, { action, month, data });
  const create = async (type, name, amount) => {
    await page.locator('#btn-header-new-account').click(); const modal = page.locator('#account-modal-box');
    if (type) await modal.getByRole('button', { name: type, exact: type === 'Cartão' }).click();
    await modal.locator('input[type=text]').fill(name);
    if (amount !== undefined) await modal.locator('input[type=number]').first().fill(String(amount));
    await modal.locator('#btn-save-account-modal').click(); await modal.waitFor({ state: 'hidden' }); await sync();
  };
  try {
    const isolated = await context.request.get('http://127.0.0.1:3100/api/finance?month=2026-09');
    assert.equal(isolated.headers()['x-contas-tatu-isolated'], 'true', 'Refusing writes outside isolated PGlite');
    await page.goto('http://127.0.0.1:3100'); await page.locator('#tab-accounts').click(); await sync();
    let view = await read('2026-09');
    assert.equal(view.accounts.length, 0); assert.equal(view.state.categories.length, 7);
    assert.equal(await page.evaluate(key => localStorage.getItem(key), key), sentinel);
    assert.equal(await page.locator('.account-tile').count(), 0);
    flows.push('Empty database and seven real categories; legacy localStorage untouched, no demo seeded');
    await create(null, 'Conta navegador', 100);
    let tile = page.locator('.account-tile').filter({ hasText: 'Conta navegador' });
    await tile.getByTitle('Editar informações da conta').click();
    await page.locator('#account-modal-box input[type=number]').first().fill('120');
    await page.locator('#btn-save-account-modal').click(); await page.locator('#account-modal-box').waitFor({ state: 'hidden' }); await sync();
    await tile.getByRole('button', { name: 'Marcar como pago', exact: true }).click(); await sync();
    view = await read('2026-09'); assert.equal(view.accounts[0].amount, 120); assert.equal(view.accounts[0].status, 'pago');
    await page.locator('#tab-history').click(); await page.getByRole('button', { name: 'Fechar mês', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Fechar mês', exact: true }).click(); await sync();
    await page.reload(); await sync(); await page.locator('#tab-history').click();
    await page.getByRole('button', { name: 'Reabrir mês', exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Reabrir mês', exact: true }).click(); await sync();
    assert.equal((await read('2026-09')).state.closedMonthHistory['2026-09'].length, 1);
    await page.getByRole('button', { name: 'Anual', exact: true }).click();
    assert.ok((await page.locator('.history-year-total').innerText()).includes('120,00'));
    flows.push('UI creation, edit, payment, close, reload, reopen and annual history persisted via API');
    await page.locator('#tab-accounts').click(); await create('Fixa', 'Recorrente navegador', 80);
    await create('Cartão', 'Cartão navegador');
    view = await read('2026-09'); const cardId = view.state.creditCards[0].id;
    await command('expense.create', '2026-08', { cardId, description: 'Agosto isolado', amount: 1000 });
    await command('payment', '2026-08', { id: cardId, type: 'credit_card', status: 'parcial', amount: 900 });
    await command('expense.create', '2026-09', { cardId, description: 'Setembro isolado', amount: 1900 });
    await page.reload(); await sync(); await page.locator('#tab-accounts').click();
    await page.getByLabel('Opções de pagamento de Cartão navegador', { exact: true }).click();
    await page.getByRole('button', { name: 'Registrar pagamento parcial', exact: true }).click();
    await page.locator('#payment-value').fill('1500'); await page.getByRole('button', { name: 'Confirmar pagamento' }).click(); await sync();
    assert.equal((await read('2026-10')).accounts.find(a => a.type === 'credit_card').amount, 500);
    await command('payment', '2026-10', { id: cardId, type: 'credit_card', status: 'pago' });
    assert.equal((await read('2026-11')).accounts.find(a => a.type === 'credit_card').amount, 0);
    flows.push('Card partial 900/1000 then 1500/2000 carries only 500; full settlement clears balance');
    await page.reload(); await sync(); await page.locator('#tab-accounts').click();
    await create('Parcelada', 'Plano navegador', 300);
    tile = page.locator('.account-tile').filter({ hasText: 'Plano navegador' }); await tile.getByTitle('Editar informações da conta').click();
    await page.getByLabel('Motivo da alteração').fill('Quitação isolada');
    await page.getByRole('button', { name: 'Quitar antecipadamente', exact: true }).click();
    await page.getByRole('button', { name: 'Confirmar quitação', exact: true }).click(); await page.locator('#account-modal-box').waitFor({ state: 'hidden' }); await sync();
    assert.equal((await read('2026-09')).state.installmentPurchases[0].versions.at(-1).operation, 'payoff');
    flows.push('Installment created and paid off through UI with temporal event');
    await page.locator('#btn-settings-header').click(); await page.getByRole('button', { name: 'Nova Categoria', exact: true }).click();
    await page.getByPlaceholder('Ex: Casa, Mercado, Manoela, Antônio, Lazer').fill('Categoria navegador');
    await page.getByRole('button', { name: 'Criar Categoria', exact: true }).click(); await sync();
    assert.equal((await read('2026-09')).state.categories.length, 8);
    await page.getByLabel('Fechar configurações').click();
    flows.push('Category creation persisted without localStorage');
    await page.locator('#btn-next-month').click(); await sync();
    await page.locator('#btn-next-month').click(); await sync();
    await create('Parcelada', 'Plano temporal', 600);
    tile = page.locator('.account-tile').filter({ hasText: 'Plano temporal' });
    await tile.getByTitle('Editar informações da conta').click();
    await page.locator('#account-modal-box select').first().selectOption(cardId);
    await page.getByLabel('Motivo da alteração').fill('Vincular ao cartão');
    await page.locator('#btn-save-account-modal').click(); await page.locator('#account-modal-box').waitFor({ state: 'hidden' }); await sync();
    let temporal = (await read('2026-11')).state.installmentPurchases.find(p => p.description === 'Plano temporal');
    assert.equal(temporal.versions.at(-1).creditCardId, cardId);
    await page.locator('#btn-expand-card-' + cardId).click();
    await page.getByTitle('Editar compra da fatura').click();
    await page.getByLabel('Local de lançamento', { exact: true }).selectOption('');
    await page.getByLabel('Motivo da alteração').fill('Voltar a avulso');
    await page.locator('#btn-save-card-purchase').click(); await page.locator('#card-purchase-modal-box').waitFor({ state: 'hidden' }); await sync();
    tile = page.locator('.account-tile').filter({ hasText: 'Plano temporal' });
    await tile.getByTitle('Editar informações da conta').click();
    await page.getByLabel('Alcance da edição').selectOption('correct');
    await page.getByLabel('Motivo da alteração').fill('Corrigir só novembro');
    await page.locator('#account-modal-box input[type=number]').first().fill('700');
    await page.locator('#btn-save-account-modal').click(); await page.locator('#account-modal-box').waitFor({ state: 'hidden' }); await sync();
    temporal = (await read('2026-11')).state.installmentPurchases.find(p => p.id === temporal.id);
    assert.equal(temporal.versions.at(-1).operation, 'correction');
    await page.locator('#btn-next-month').click(); await sync();
    await page.locator('.account-tile').filter({ hasText: 'Plano temporal' }).getByTitle('Editar informações da conta').click();
    await page.getByLabel('Motivo da alteração').fill('Encerrar a partir de dezembro');
    await page.getByRole('button', { name: 'Cancelar parcelas futuras', exact: true }).click();
    await page.getByRole('button', { name: 'Confirmar cancelamento', exact: true }).click();
    await page.locator('#account-modal-box').waitFor({ state: 'hidden' }); await sync();
    assert.equal((await read('2026-12')).accounts.some(a => a.name === 'Plano temporal'), false);
    assert.equal((await read('2026-11')).accounts.find(a => a.name === 'Plano temporal').amount, 70);
    await page.locator('#btn-current-month-reset').click(); await sync();
    flows.push('Month navigation, standalone/card transfers, one-month correction and future cancellation preserve November');

    // A separate command changes revision while an already-open form stays intact.
    await page.locator('#btn-header-new-account').click(); await page.locator('#account-modal-box input[type=text]').fill('Conflito');
    await page.locator('#account-modal-box input[type=number]').first().fill('1');
    await command('simple.create', '2026-09', { name: 'Outra sessão', value: 2 });
    await page.locator('#btn-save-account-modal').click(); await page.getByRole('alert').filter({ hasText: 'outra sessão' }).waitFor();
    assert.equal((await read('2026-09')).state.simpleAccounts.some(a => a.name === 'Conflito'), false);
    assert.equal(await page.locator('#account-modal-box').isVisible(), true);
    await page.locator('#account-modal-box').getByRole('button', { name: 'Cancelar', exact: true }).click();
    flows.push('Revision conflict refreshes server state and does not silently repeat write');
    await page.route('**/api/finance?*', route => route.fulfill({ status: 500, body: '{"error":"sensitive-raw-database-error"}' }));
    await page.reload(); await page.getByRole('button', { name: 'Tentar novamente', exact: true }).waitFor();
    assert.ok(!(await page.locator('body').innerText()).includes('sensitive-raw'));
    await page.unroute('**/api/finance?*'); await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click(); await sync();
    assert.equal(await page.evaluate(key => localStorage.getItem(key), key), sentinel);
    assert.deepEqual(errors, []); flows.push('Sanitized API failure and explicit recovery; storage preserved');
    console.log(JSON.stringify({ passed: true, flows }, null, 2));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
